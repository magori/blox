package ch.magori.blox.core.garden

import ch.magori.blox.core.game.model.Piece
import ch.magori.blox.core.music.Note
import ch.magori.blox.core.music.Pitch
import ch.magori.blox.core.music.Score
import ch.magori.blox.core.music.Voice
import ch.magori.blox.core.music.bassVoice
import ch.magori.blox.core.music.melodyVoice
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test
import org.junit.jupiter.params.ParameterizedTest
import org.junit.jupiter.params.provider.CsvSource
import org.junit.jupiter.params.provider.EnumSource
import java.math.BigDecimal

class GardenScoreTest {
    @Test
    fun `a cell plays its note for its eighth`() {
        // Given: an I lying on row 2, from column 8 to column 11, in the calm mood
        val garden = Garden.parse(
            """
            ................
            ................
            ........IIII....
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            """,
        )

        // When
        val score = garden.toScore()

        // Then: the cell of column 8 plays the note of row 2 during the ninth eighth, from beat 4 to beat 4.5, on the
        // wave of the generated melodies
        val voice = score.voiceOf(GardenMood.CALM.pitchAt(2))
        assertThat(voice.sounding()).contains(Sounding(start = 4.0, pitch = GardenMood.CALM.pitchAt(2), beats = 0.5))
        assertThat(voice.waveform).isEqualTo(melodyVoice(listOf(Note(null, 1.0))).waveform)
    }

    @Test
    fun `a standing piece plays its notes as a rising arpeggio within the eighth`() {
        // Given: an I standing in column 5, from row 2 down to row 5
        val garden = Garden.parse(
            """
            ................
            ................
            .....I..........
            .....I..........
            .....I..........
            .....I..........
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            """,
        )

        // When
        val score = garden.toScore()

        // Then: the four notes share the sixth eighth, from beat 2.5, a quarter of it each, from the lowest one up
        val notes = (5 downTo 2).map(GardenMood.CALM::pitchAt).flatMap { score.voiceOf(it).sounding() }
        assertThat(notes).containsExactly(
            Sounding(start = 2.5, pitch = GardenMood.CALM.pitchAt(5), beats = 0.125),
            Sounding(start = 2.625, pitch = GardenMood.CALM.pitchAt(4), beats = 0.125),
            Sounding(start = 2.75, pitch = GardenMood.CALM.pitchAt(3), beats = 0.125),
            Sounding(start = 2.875, pitch = GardenMood.CALM.pitchAt(2), beats = 0.125),
        )
    }

    @Test
    fun `a column of three cells keeps the length of the bar exact`() {
        // Given: a T pointing left, its column of three cells in column 13, from row 4 down to row 6
        val garden = Garden.parse(
            """
            ................
            ................
            ................
            ................
            .............T..
            ............TT..
            .............T..
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            """,
        )

        // When
        val score = garden.toScore()

        // Then: a third of an eighth does not fall right in a Double, but each part ends where it should, the last one
        // on the end of the fourteenth eighth, and every voice lasts exactly 2 bars
        val triplet = (6 downTo 4).map { row ->
            score.voiceOf(GardenMood.CALM.pitchAt(row)).sounding().single { it.start >= 6.5 }
        }
        assertThat(triplet.map { it.start + it.beats }).containsExactly(6.5 + 0.5 / 3, 6.5 + 2 * 0.5 / 3, 7.0)
        assertThat(score.voices).allSatisfy { assertThat(it.beats).isEqualTo(8.0) }
    }

    @Test
    fun `a piece with one cell per column plays its notes column after column`() {
        // Given: an I lying on row 7, from column 4 to column 7
        val garden = Garden.parse(
            """
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ....IIII........
            ................
            ................
            ................
            ................
            ................
            ................
            """,
        )

        // When
        val score = garden.toScore()

        // Then: four eighths one after the other, repeated without a tie, not one note of 2 beats
        val note = GardenMood.CALM.pitchAt(7)
        assertThat(score.voiceOf(note).sounding()).containsExactly(
            Sounding(start = 2.0, pitch = note, beats = 0.5),
            Sounding(start = 2.5, pitch = note, beats = 0.5),
            Sounding(start = 3.0, pitch = note, beats = 0.5),
            Sounding(start = 3.5, pitch = note, beats = 0.5),
        )
    }

    @Test
    fun `two pieces in the same column sound together`() {
        // Given: an I lying on row 1, from column 0 to column 3, and an O on rows 9 and 10, in columns 3 and 4
        val garden = Garden.parse(
            """
            ................
            IIII............
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ...OO...........
            ...OO...........
            ................
            ................
            ................
            """,
        )

        // When
        val score = garden.toScore()

        // Then: in column 3, from beat 1.5, the I plays its whole eighth while the O plays its two notes,
        // each by its rule
        val notesOfColumn3 = listOf(1, 10, 9)
            .map(GardenMood.CALM::pitchAt)
            .flatMap { score.voiceOf(it).sounding() }
            .filter { it.start in 1.5..<2.0 }
        assertThat(notesOfColumn3).containsExactly(
            Sounding(start = 1.5, pitch = GardenMood.CALM.pitchAt(1), beats = 0.5),
            Sounding(start = 1.5, pitch = GardenMood.CALM.pitchAt(10), beats = 0.25),
            Sounding(start = 1.75, pitch = GardenMood.CALM.pitchAt(9), beats = 0.25),
        )
    }

    @Test
    fun `an empty garden plays the bass alone`() {
        // Given: nothing placed, in the calm mood, whose chords are I, vi, IV and V on C3
        val garden = Garden.EMPTY

        // When
        val score = garden.toScore()

        // Then: one voice, on the wave of the generated basses, the root of each chord a quarter note per beat,
        // from C2
        val bass = score.voices.single()
        assertThat(bass.waveform).isEqualTo(bassVoice(listOf(Note(null, 1.0))).waveform)
        assertThat(bass.notes).containsExactlyElementsOf(
            "C2 C2 A2 A2 F2 F2 G2 G2".split(" ").map { Note(Pitch.parse(it), 1.0) },
        )
    }

    @ParameterizedTest(name = "{0}: {1}")
    @CsvSource(
        "JOYFUL, C2 C2 G2 G2 A2 A2 F2 F2",
        "CALM, C2 C2 A2 A2 F2 F2 G2 G2",
        "MYSTERIOUS, C2 C2 A#2 A#2 G#2 G#2 G2 G2",
        "EPIC, C2 C2 G#2 G#2 D#2 D#2 A#2 A#2",
    )
    fun `the bass plays the root of each chord in the octave from C2, whatever the tonic of the mood`(
        mood: GardenMood,
        roots: String,
    ) {
        // Given: an empty garden in this mood, its tonic on C4, or on C3 for the calm one
        val garden = Garden.EMPTY.withMood(mood)

        // When
        val score = garden.toScore()

        // Then: the bass of every mood sits in the same octave, two below C4
        val bass = score.voices.single().notes.map { it.pitch }
        assertThat(bass).containsExactlyElementsOf(roots.split(" ").map(Pitch::parse))
    }

    @ParameterizedTest
    @EnumSource(GardenMood::class)
    fun `the score lasts two bars of four beats at the tempo of the mood`(mood: GardenMood) {
        // Given: a T standing on its tip, in this mood
        val garden = Garden.parse(
            """
            ................
            ................
            ................
            ..TTT...........
            ...T............
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            """,
        ).withMood(mood)

        // When
        val score = garden.toScore()

        // Then
        assertThat(score.bpm).isEqualTo(mood.tempo)
        assertThat(score.beatsPerBar).isEqualTo(4)
        assertThat(score.voices).allSatisfy { assertThat(it.beats).isEqualTo(8.0) }
    }

    @Test
    fun `two pieces on the same row play in one voice, with a rest between them`() {
        // Given: two I lying on row 3, one from column 0 to column 3, the other from column 10 to column 13
        val garden = Garden.parse(
            """
            ................
            ................
            ................
            IIII......1111..
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            """,
        )

        // When
        val score = garden.toScore()

        // Then: a single voice for the note of row 3, its eight eighths from beats 0 and 5, lasting 2 bars
        val note = GardenMood.CALM.pitchAt(3)
        val voice = score.voiceOf(note)
        assertThat(voice.sounding().map(Sounding::start)).containsExactly(0.0, 0.5, 1.0, 1.5, 5.0, 5.5, 6.0, 6.5)
        assertThat(voice.beats).isEqualTo(8.0)
    }

    @Test
    fun `the score does not depend on the order in which the pieces were placed`() {
        // Given: an I and an O, placed in one order and in the other
        val pieces = Garden.parse(
            """
            ................
            IIII............
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            .....OO.........
            .....OO.........
            ................
            ................
            ................
            """,
        ).pieces.toList()
        val oneWay = pieces.fold(Garden.EMPTY) { garden, piece -> garden.placed(piece) }
        val otherWay = pieces.reversed().fold(Garden.EMPTY) { garden, piece -> garden.placed(piece) }

        // When
        val scores = listOf(oneWay, otherWay).map(Garden::toScore)

        // Then: the same garden, the same score
        assertThat(scores[0]).isEqualTo(scores[1])
    }

    @Test
    fun `fourteen notes at once and the bass reach full scale without going above it`() {
        // Given: fourteen I lying on top of each other in the first four columns, a note on every row at once
        val garden = Garden.parse(
            """
            IIII............
            1111............
            IIII............
            1111............
            IIII............
            1111............
            IIII............
            1111............
            IIII............
            1111............
            IIII............
            1111............
            IIII............
            1111............
            """,
        )
        // When
        val score = garden.toScore()

        // Then: its fourteen notes and its bass, all at once, add up to full scale, loud as can be but never clipped
        assertThat(score.voices).hasSize(15)
        assertThat(score.loudestMoment()).isEqualByComparingTo(FULL_SCALE)
    }

    /** A note heard: its [pitch] from beat [start] for [beats] beats. */
    private data class Sounding(val start: Double, val pitch: Pitch, val beats: Double)

    /** The notes of this voice that are not rests, with the beat each one starts on. */
    private fun Voice.sounding(): List<Sounding> {
        val starts = notes.runningFold(0.0) { beats, note -> beats + note.beats }
        return notes.zip(starts).mapNotNull { (note, start) -> note.pitch?.let { Sounding(start, it, note.beats) } }
    }

    private fun Garden.placed(piece: Piece): Garden = (place(piece) as GardenPlacement.Placed).garden

    /** The one voice of this score that plays [pitch]: the voice of its row. */
    private fun Score.voiceOf(pitch: Pitch): Voice = voices.single { voice -> voice.notes.any { it.pitch == pitch } }

    /**
     * The highest amplitude this score can reach once mixed: the volumes of the voices that sound at the same moment,
     * added up, at its loudest moment, in decimals so that adding them rounds nothing. The square and the triangle
     * waves each reach their volume.
     */
    private fun Score.loudestMoment(): BigDecimal {
        val notes = voices.map { it to it.sounding() }
        return notes.flatMap { (_, sounding) -> sounding.map(Sounding::start) }.distinct().maxOf { beat ->
            notes
                .filter { (_, sounding) -> sounding.any { beat >= it.start && beat < it.start + it.beats } }
                .sumOf { (voice, _) -> voice.volume.toBigDecimal() }
        }
    }

    private companion object {
        /** Full scale: the amplitude past which `mix`, in `core:audio`, clips the samples. */
        val FULL_SCALE: BigDecimal = BigDecimal.ONE
    }
}
