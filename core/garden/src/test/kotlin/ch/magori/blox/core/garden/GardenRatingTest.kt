package ch.magori.blox.core.garden

import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test

class GardenRatingTest {
    @Test
    fun `the notes of the chord of their group are counted cell by cell`() {
        // Given, joyful: a T under C major, three cells on E4 and one on D4; a T under G major, three cells on D4 and
        // one on C4. Each T counts 3 under the chord of its own group only: the first one 1 under G major and 0 under
        // F major, the second one 1 under C major, A minor or F major.
        val garden = Garden.parse(
            """
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            TTT.............
            .T..TTT.........
            .....T..........
            """,
        ).withMood(GardenMood.JOYFUL)

        // When
        val rating = GardenRating.of(garden)

        // Then: E4 is a note of C major, D4 one of G major
        assertThat(rating.chordNotes).isEqualTo(6)
    }

    @Test
    fun `the groups holding a note of their chord are counted`() {
        // Given, joyful: the T and the O hold a note of their chord, the I, all on D4 under A minor, none; the last
        // group is empty
        val garden = Garden.parse(
            """
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            TTT.............
            .T..OO..IIII....
            ....OO..........
            """,
        ).withMood(GardenMood.JOYFUL)

        // When
        val rating = GardenRating.of(garden)

        // Then
        assertThat(rating.chordGroups).isEqualTo(2)
    }

    @Test
    fun `each type of piece is counted once`() {
        // Given: two O and a T
        val garden = Garden.parse(
            """
            OO..OO..TTT.....
            OO..OO...T......
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            """,
        )

        // When
        val rating = GardenRating.of(garden)

        // Then
        assertThat(rating.types).isEqualTo(2)
    }

    @Test
    fun `the gap between the fullest and the emptiest group is counted in cells`() {
        // Given: the I lies over the first two groups, two cells in each; the O fills the third group with 4 cells;
        // the last group is empty
        val garden = Garden.parse(
            """
            ..IIII..........
            ................
            ........OO......
            ........OO......
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            ................
            """,
        )

        // When
        val rating = GardenRating.of(garden)

        // Then
        assertThat(rating.imbalance).isEqualTo(4)
    }

    @Test
    fun `the points add 10 per note of the chord, 30 per group holding one, 10 per type, minus 5 per cell of gap`() {
        // Given
        val rating = GardenRating(chordNotes = 5, chordGroups = 2, types = 3, imbalance = 4)

        // Then: 50 + 60 + 30 - 20
        assertThat(rating.points).isEqualTo(120)
    }
}
