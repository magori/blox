package ch.magori.blox.core.audio

/** What a music written as a ringtone rings for (ADR 0031): the calls, or the alarms of the Clock. */
public enum class RingtoneKind {
    /** The ringtone of the calls, in `Ringtones/BloX/`. */
    RINGTONE,

    /** The sound of an alarm, in `Alarms/BloX/`, chosen in the Clock alarm by alarm. */
    ALARM,
}
